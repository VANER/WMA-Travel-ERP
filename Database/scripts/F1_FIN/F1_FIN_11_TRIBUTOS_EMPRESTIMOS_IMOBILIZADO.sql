WITH integridade AS (
    SELECT
        (
            SELECT COUNT(*)
            FROM pg_constraint con
            JOIN pg_class c
              ON c.oid = con.conrelid
            JOIN pg_namespace n
              ON n.oid = c.relnamespace
            WHERE n.nspname = 'financeiro'
              AND c.relname IN (
                  'tributo',
                  'emprestimo',
                  'emprestimo_parcela',
                  'ativo_imobilizado',
                  'depreciacao_ativo'
              )
              AND NOT con.convalidated
        ) AS constraints_nao_validadas,

        (
            SELECT COUNT(*) FROM financeiro.tributo
            WHERE codigo = 'F1FIN11-TRIB'
        ) AS teste_tributo,

        (
            SELECT COUNT(*) FROM financeiro.emprestimo
            WHERE descricao = 'Teste F1-FIN.11'
        ) AS teste_emprestimo,

        (
            SELECT COUNT(*) FROM financeiro.ativo_imobilizado
            WHERE codigo = 'F1FIN11-ATIVO'
        ) AS teste_ativo
)
SELECT
    CASE WHEN to_regclass('financeiro.tributo') IS NOT NULL THEN 1 ELSE 0 END AS tributo,
    CASE WHEN to_regclass('financeiro.emprestimo') IS NOT NULL THEN 1 ELSE 0 END AS emprestimo,
    CASE WHEN to_regclass('financeiro.emprestimo_parcela') IS NOT NULL THEN 1 ELSE 0 END AS emprestimo_parcela,
    CASE WHEN to_regclass('financeiro.ativo_imobilizado') IS NOT NULL THEN 1 ELSE 0 END AS ativo_imobilizado,
    CASE WHEN to_regclass('financeiro.depreciacao_ativo') IS NOT NULL THEN 1 ELSE 0 END AS depreciacao_ativo,
    i.constraints_nao_validadas,
    i.teste_tributo,
    i.teste_emprestimo,
    i.teste_ativo,
    CASE
        WHEN to_regclass('financeiro.tributo') IS NOT NULL
         AND to_regclass('financeiro.emprestimo') IS NOT NULL
         AND to_regclass('financeiro.emprestimo_parcela') IS NOT NULL
         AND to_regclass('financeiro.ativo_imobilizado') IS NOT NULL
         AND to_regclass('financeiro.depreciacao_ativo') IS NOT NULL
         AND i.constraints_nao_validadas = 0
         AND i.teste_tributo = 0
         AND i.teste_emprestimo = 0
         AND i.teste_ativo = 0
        THEN 'F1_FIN_11_APROVADA'
        ELSE 'F1_FIN_11_PENDENTE'
    END AS status
FROM integridade i;


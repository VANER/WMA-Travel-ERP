DO $$
DECLARE
    v_invalid bigint;
BEGIN
    SELECT COUNT(*)
    INTO v_invalid
    FROM pg_constraint con
    JOIN pg_class c
      ON c.oid = con.conrelid
    JOIN pg_namespace n
      ON n.oid = c.relnamespace
    WHERE n.nspname = 'financeiro'
      AND c.relname IN (
          'tributo',
          'emprestimo',
          'emprestimo_parcela',
          'ativo_imobilizado',
          'depreciacao_ativo'
      )
      AND NOT con.convalidated;

    IF v_invalid <> 0 THEN
        RAISE EXCEPTION
            'F1-FIN.11 abortada: % constraints nao validadas.',
            v_invalid;
    END IF;

    IF EXISTS (
        SELECT 1 FROM financeiro.tributo WHERE codigo = 'F1FIN11-TRIB'
    )
    OR EXISTS (
        SELECT 1 FROM financeiro.emprestimo WHERE descricao = 'Teste F1-FIN.11'
    )
    OR EXISTS (
        SELECT 1 FROM financeiro.ativo_imobilizado WHERE codigo = 'F1FIN11-ATIVO'
    ) THEN
        RAISE EXCEPTION
            'F1-FIN.11 abortada: dados de teste permaneceram.';
    END IF;
END
$$;


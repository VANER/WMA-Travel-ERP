BEGIN
    IF current_database() <> 'wma_travel' THEN
        RAISE EXCEPTION
            'F1-FIN.11 abortada: banco atual %, esperado wma_travel.',
            current_database();
    END IF;

    IF to_regclass('financeiro.lancamento') IS NULL THEN
        RAISE EXCEPTION
            'F1-FIN.11 abortada: financeiro.lancamento ausente.';
    END IF;

    IF to_regclass('public.empresa') IS NULL THEN
        RAISE EXCEPTION
            'F1-FIN.11 abortada: public.empresa ausente.';
    END IF;

    SELECT count(*)
    INTO v_count
    FROM public.empresa;

    IF v_count = 0 THEN
        RAISE EXCEPTION
            'F1-FIN.11 abortada: public.empresa sem registros.';
    END IF;
END

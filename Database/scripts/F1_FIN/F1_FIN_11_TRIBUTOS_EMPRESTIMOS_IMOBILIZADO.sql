\echo ''
\echo '============================================================'
\echo ' 12 - REAUDITORIA DE CONSTRAINTS'
\echo '============================================================'

SELECT
    c.relname AS table_name,
    COUNT(*) AS constraints,
    COUNT(*) FILTER (WHERE NOT con.convalidated) AS nao_validadas
FROM pg_constraint con
JOIN pg_class c
  ON c.oid = con.conrelid
JOIN pg_namespace n
  ON n.oid = c.relnamespace
WHERE n.nspname = 'financeiro'
  AND c.relname IN (
      'tributo',
      'emprestimo',
      'emprestimo_parcela',
      'ativo_imobilizado',
      'depreciacao_ativo'
  )
GROUP BY c.relname
ORDER BY c.relname;

